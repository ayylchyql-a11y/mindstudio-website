/**
 * 给 `metadata.alternates.languages` 用的 hreflang 表。
 * 传路径模板，`{lang}` 会被替换成路由段。
 *
 * 🩸 别再手写 `{ en: "/en", "zh-CN": "/zh" }` —— 加语言时那种写法必漏
 *   （2026-08-26 从 2 语言扩到 12 时，三处都还停在两条）。
 */
export function hreflangMap(pathTemplate: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const loc of locales) {
    out[localeMeta[loc].htmlLang] = pathTemplate.replace("{lang}", loc);
  }
  out["x-default"] = pathTemplate.replace("{lang}", defaultLocale);
  return out;
}

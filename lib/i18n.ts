/**
 * 回落链：繁中缺了先找简中，其余一律回落英文。
 *
 * ⭐ 宣传图/截图也走这条链 —— 用户 2026-08-26 拍板：**除中文外一律套用英文那套图**。
 *    所以 `data/apps.ts` 里的 `shot`/`gallery.src`/`slides.src` 只需填 en 与 zh，
 *    其余十种语言自动拿英文图，不用为每种语言各存一份。
 */
const fallbackOf: Partial<Record<Locale, Locale>> = { "zh-tw": "zh" };

/**
 * 文案的多语言值。**只有 `en` 是必填**，其余语言缺了就按 `fallbackOf` 回落。
 *
 * 🩸 **别改回 `Record<Locale, string>`**：那样每加一种语言，`data/*.ts` 里
 *    每一处文案都得同步补齐，否则整站编译不过——12 语言时是几百处，
 *    而隐私政策这种长文根本不该机翻十份。读取一律走 `pick()`，别写 `value[lang]`。
 */
export type Localized = { en: string } & Partial<Record<Locale, string>>;

/** 取某种语言的文案，缺了按回落链退。**所有 `Localized` 的读取都走这里。** */
export function pick(value: Localized | undefined, lang: Locale): string {
  if (!value) return "";
  const direct = value[lang];
  if (direct !== undefined) return direct;
  const fb = fallbackOf[lang];
  if (fb !== undefined) {
    const viaFb = value[fb];
    if (viaFb !== undefined) return viaFb;
  }
  return value.en;
}

/** 这条文案有没有当前语言的原文（用来显示「本页仅英文」之类的提示）。 */
export function hasLocale(value: Localized | undefined, lang: Locale): boolean {
  if (!value) return false;
  if (value[lang] !== undefined) return true;
  const fb = fallbackOf[lang];
  return fb !== undefined && value[fb] !== undefined;
}


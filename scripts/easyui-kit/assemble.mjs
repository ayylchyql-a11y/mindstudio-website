// 把 kit/out-*.json（每条的文案）+ heights.json + code-files.json 拼成
// data/effects-kit.ts。用法：node scripts/easyui-kit/assemble.mjs
import fs from 'node:fs';
import path from 'node:path';

const MS = import.meta.dirname;
const SITE = path.resolve(MS, '../..');
const groups = JSON.parse(fs.readFileSync(path.join(MS, 'kit/groups.json'), 'utf8'));
const heights = JSON.parse(fs.readFileSync(path.join(MS, 'heights.json'), 'utf8'));
const codeFiles = JSON.parse(fs.readFileSync(path.join(MS, 'code-files.json'), 'utf8'));
const groupOf = {};
for (const [g, ids] of Object.entries(groups)) for (const id of ids) groupOf[id] = g.toLowerCase();

const rows = [];
for (const f of fs.readdirSync(path.join(MS, 'kit')).filter((f) => /^out-.*\.json$/.test(f)).sort()) {
  rows.push(...JSON.parse(fs.readFileSync(path.join(MS, 'kit', f), 'utf8')));
}
const byId = Object.fromEntries(rows.map((r) => [r.id, r]));
const want = Object.keys(groupOf);
const missing = want.filter((id) => !byId[id]);
if (missing.length) throw new Error(`no copy for: ${missing.join(' ')}`);

const BAD = /\b(smooth|silky|premium|seamless|modern|Apple-grade)\b/i;
const BRANDS = /\b(Stripe|PayPal|Ferrari|Dribbble|Wise)\b/;
const problems = [];
const entries = want.map((id) => {
  const r = byId[id];
  for (const k of ['title', 'gist']) for (const l of ['en', 'zh', 'zh-tw']) if (!r[k]?.[l]) problems.push(`${id}: ${k}.${l} missing`);
  if (!['self', 'hover', 'click', 'scroll'].includes(r.plays)) problems.push(`${id}: plays=${r.plays}`);
  if (!/^#[0-9a-f]{6}$/i.test(r.accent ?? '')) problems.push(`${id}: accent=${r.accent}`);
  if (!(r.anatomy?.length >= 3)) problems.push(`${id}: anatomy ${r.anatomy?.length}`);
  if (!(r.tokens?.length >= 3)) problems.push(`${id}: tokens ${r.tokens?.length}`);
  if (!r.prompt || r.prompt.length < 300) problems.push(`${id}: prompt short`);
  if (!r.blurb) problems.push(`${id}: blurb missing`);
  if (!codeFiles[id]) problems.push(`${id}: no codeFile`);
  const prose = [r.gist?.en, r.blurb, r.prompt, ...(r.anatomy ?? [])].join(' ');
  // <code>…</code> 和引号里的是 API 取值（behavior: "smooth"），不算空话
  const plain = prose.replace(/<code>.*?<\/code>/g, '').replace(/(["'])[^"']*\1/g, '');
  if (BAD.test(plain)) problems.push(`${id}: vague word ${plain.match(BAD)[0]}`);
  if (BRANDS.test(prose)) problems.push(`${id}: brand ${prose.match(BRANDS)[0]}`);
  const h = Math.min(760, Math.max(360, Math.ceil(((heights[id] ?? 300) + 96) / 10) * 10));
  return {
    slug: id, category: 'kit', group: groupOf[id], date: '2026-10-23', plays: r.plays,
    title: r.title, gist: r.gist, height: h, accent: r.accent.toLowerCase(),
    codeFile: codeFiles[id],
    source: { label: 'EasyUI by Suraj Maurya · MIT', url: `https://easyui.site/components/${id}` },
    anatomy: r.anatomy, tokens: r.tokens, prompt: r.prompt,
    ...(r.caveats?.length ? { caveats: r.caveats } : {}),
  };
});
if (problems.length) { console.error(problems.join('\n')); process.exitCode = 1; }

const blurbs = Object.fromEntries(want.map((id) => [id, byId[id].blurb]));
const out = `// AUTO-GENERATED by scripts/easyui-kit/assemble.mjs — 别手改，改 scripts/easyui-kit/kit/out-*.json 再重新生成。
// 「组件库」分类：EasyUI（MIT, Suraj Maurya）原版组件打包进 public/effects/_easyui/，
// 打包：scripts/easyui-kit/build.mjs。这里只有设计库自己写的文案（标题 / 一句话 / 拆解 / 参数 / 提示词 / 橱窗介绍）。
import type { Effect } from "./effects";

export const kitEffects: Effect[] = ${JSON.stringify(entries, null, 2)};

export const kitBlurbs: Record<string, string> = ${JSON.stringify(blurbs, null, 2)};
`;
fs.writeFileSync(path.join(SITE, 'data/effects-kit.ts'), out);
console.log(`wrote ${entries.length} entries · problems ${problems.length}`);
